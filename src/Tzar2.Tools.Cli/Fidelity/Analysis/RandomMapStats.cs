using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Tzar2.Content.MapGen;
using Tzar2.Formats;
using Tzar2.Formats.Maps;
using Tzar2.Tools.Cli.Fidelity.Yaml;

namespace Tzar2.Tools.Cli.Fidelity.Analysis;

/// <summary>
/// <c>t2 fidelity maps</c> (RE-10, mapgen.statistics): statistics of random maps the operator generated in the original
/// and saved as <c>&lt;type&gt;-*.wmp</c> (editor session, ADR 0113), read with the M4-A map reader. Numbers only: per map
/// the side, the kingdoms' castles, the castles' mean nearest-neighbour spacing as a share of the side, and the gold,
/// stone and tree objects per kingdom. The maps themselves stay local.
/// </summary>
internal static class RandomMapStats
{
    public sealed record Stats(string File, RandomMapType Type, int Side, int Castles, double Spacing, double GoldPerKingdom, double StonePerKingdom, double TreesPerKingdom);

    public static Stats? Measure(string file, byte[] data)
    {
        string name = Path.GetFileNameWithoutExtension(file);
        if (!RandomMapNames.TryParse(name.Split('-')[0], out RandomMapType type))
        {
            return null;
        }

        LegacyMap map = LegacyMapReader.ReadMap(data);
        var castles = map.Objects.Where(o => o.ClassName.Contains("castle", StringComparison.OrdinalIgnoreCase)).Select(o => (o.X, o.Y)).ToList();
        int kingdoms = Math.Max(1, castles.Count);
        int Count(string part) => map.Objects.Count(o => o.ClassName.Contains(part, StringComparison.OrdinalIgnoreCase));
        return new Stats(Path.GetFileName(file), type, map.Side, castles.Count, MeanNearest(castles) / Math.Max(1, map.Side),
            Count("gold") / (double)kingdoms, Count("stone") / (double)kingdoms, Count("tree") / (double)kingdoms);
    }

    /// <summary>Mean distance (tiles) from each point to its nearest other point; 0 for fewer than two.</summary>
    public static double MeanNearest(IReadOnlyList<(int X, int Y)> points)
    {
        if (points.Count < 2)
        {
            return 0;
        }

        return points.Average(p => points.Where(q => q != p).Min(q => Math.Sqrt(((double)(p.X - q.X) * (p.X - q.X)) + ((double)(p.Y - q.Y) * (p.Y - q.Y)))));
    }

    /// <summary>Writes <c>random-maps.yaml</c> into <paramref name="factsDir"/>; returns the maps measured.</summary>
    public static IReadOnlyList<Stats> Write(string mapsDir, string factsDir, TextWriter log)
    {
        var stats = new List<Stats>();
        foreach (string file in Directory.EnumerateFiles(mapsDir, "*.wmp").OrderBy(f => f, StringComparer.Ordinal))
        {
            try
            {
                if (Measure(file, File.ReadAllBytes(file)) is { } s)
                {
                    stats.Add(s);
                }
                else
                {
                    log.WriteLine($"skipped {Path.GetFileName(file)}: name it <type>-<n>.wmp (archipelagos, island, continental, lakes, dry)");
                }
            }
            catch (LegacyFormatException ex)
            {
                log.WriteLine($"skipped {Path.GetFileName(file)}: {ex.Message}");
            }
        }

        var w = new YamlWriter();
        w.Add("schema", FidelityAnalyzer.FactsSchema);
        w.Add("scenario", "random-maps");
        w.Add("title", "Random maps generated by the original (RE-10)");
        w.Map("provenance", p =>
        {
            p.Add("edition", "GOG v1.10 English (reference build)");
            p.Add("install_matches_reference", true);
            p.Add("method", "maps saved by the operator from the original's random-map generator, read with the M4-A map reader");
            p.Add("maps", stats.Count);
        });
        w.Map("analyses", a => a.Map("random-maps", m =>
        {
            m.Add("status", stats.Count > 0 ? "ok" : "inconclusive");
            m.Add("notes", new YamlWriter.Flow(Array.Empty<object?>()));
            m.Map("facts", f => f.Add("measurements", stats.Select(s =>
            {
                var e = new YamlWriter();
                e.Add("file", s.File);
                e.Add("type", RandomMapNames.Name(s.Type));
                e.Add("side", s.Side);
                e.Add("castles", s.Castles);
                e.Add("castle_spacing_share", Math.Round(s.Spacing, 4), "mean nearest-neighbour castle distance / side");
                e.Add("gold_per_kingdom", Math.Round(s.GoldPerKingdom, 2));
                e.Add("stone_per_kingdom", Math.Round(s.StonePerKingdom, 2));
                e.Add("trees_per_kingdom", Math.Round(s.TreesPerKingdom, 1));
                return e;
            }).ToList()));
        }));
        Directory.CreateDirectory(factsDir);
        File.WriteAllText(Path.Combine(factsDir, "random-maps.yaml"), w.ToYaml("Statistics of random maps generated by the original (t2 fidelity maps, ADR 0113); numbers only."));
        return stats;
    }
}
