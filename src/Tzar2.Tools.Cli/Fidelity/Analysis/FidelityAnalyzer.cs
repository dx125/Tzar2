using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using Tzar2.Tools.Cli.Fidelity.Scenarios;
using Tzar2.Tools.Cli.Fidelity.Yaml;

namespace Tzar2.Tools.Cli.Fidelity.Analysis;

/// <summary>The facts file written for one scenario.</summary>
internal sealed record FactsFile(string ScenarioId, string Path, IReadOnlyDictionary<string, string> Statuses);

/// <summary>
/// Turns a capture session into fact files (TDD §22.3, REQ-RE-02): one <c>&lt;scenario&gt;.yaml</c> per scenario
/// with provenance and, per analysis, its status, numbers and notes. No image data is written.
/// </summary>
internal static class FidelityAnalyzer
{
    public const string FactsSchema = "tzar2-fidelity-facts/1";

    public static AnalysisOutcome RunAnalysis(string kind, AnalysisContext ctx, IReadOnlyList<TrialData> trials) => kind switch
    {
        "capture-quality" => CaptureQuality.Run(ctx, trials),
        "colour-depth" => ColourDepth.Run(ctx, trials),
        "terrain-tiles" => TerrainTiles.Run(ctx, trials),
        "shadow-blend" => ShadowBlend.Run(ctx, trials),
        "player-colours" => PlayerColours.Run(ctx, trials),
        "unit-speed" => UnitSpeed.Run(ctx, trials),
        "attack-timing" => AttackTiming.Run(ctx, trials),
        "gather-rates" => GatherRates.Run(ctx, trials),
        "region-timing" => RegionTiming.Run(ctx, trials),
        "day-clock" => DayClock.Run(ctx, trials),
        _ => AnalysisOutcome.Skipped($"unknown analysis '{kind}'"),
    };

    /// <summary>The scenario specs stored in the session (as they were when captured).</summary>
    public static IReadOnlyList<ScenarioSpec> Scenarios(CaptureSession session)
    {
        var result = new List<ScenarioSpec>();
        foreach (string id in session.Trials.Select(t => t.Scenario).Distinct(StringComparer.Ordinal))
        {
            string? text = session.ReadText($"scenarios/{id}/scenario.yaml");
            if (text is not null)
            {
                result.Add(ScenarioLoader.ParseScenario(text, $"{id}/scenario.yaml"));
            }
        }

        return result;
    }

    public static IReadOnlyList<FactsFile> Analyze(AnalysisContext ctx, string factsDir, IReadOnlyCollection<string>? only, TextWriter progress)
    {
        Directory.CreateDirectory(factsDir);
        var written = new List<FactsFile>();
        foreach (ScenarioSpec scenario in Scenarios(ctx.Session))
        {
            if (only is { Count: > 0 } && !only.Contains(scenario.Id))
            {
                continue;
            }

            var trials = ctx.Session.Trials.Where(t => t.Scenario == scenario.Id).ToList();
            var analyses = new YamlWriter();
            var statuses = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (string kind in scenario.Analysis.Prepend("capture-quality").Distinct(StringComparer.Ordinal))
            {
                progress.WriteLine($"  {scenario.Id}: {kind} ...");
                AnalysisOutcome outcome;
                try
                {
                    outcome = RunAnalysis(kind, ctx, trials);
                }
                catch (Exception ex) when (ex is InvalidDataException or IOException or FormatException or ArgumentException or InvalidOperationException)
                {
                    outcome = new AnalysisOutcome("error", new YamlWriter(), [ex.Message]);
                }

                statuses[kind] = outcome.Status;
                analyses.Map(kind, a =>
                {
                    a.Add("status", outcome.Status);
                    a.Add("notes", new YamlWriter.Flow(outcome.Notes.Take(20).Select(n => (object?)n).ToList()));
                    a.Add("facts", outcome.Facts);
                });
                progress.WriteLine($"  {scenario.Id}: {kind} -> {outcome.Status}");
            }

            var doc = new YamlWriter();
            doc.Add("schema", FactsSchema);
            doc.Add("scenario", scenario.Id);
            doc.Add("title", scenario.Title);
            doc.Add("resolves", new YamlWriter.Flow(scenario.Resolves.Select(r => (object?)r).ToList()));
            doc.Map("provenance", p => Provenance(p, ctx.Session, trials));
            doc.Add("analyses", analyses);
            string path = Path.Combine(factsDir, scenario.Id + ".yaml");
            File.WriteAllText(path, doc.ToYaml(
                "Fidelity facts measured in the original game by the capture harness (TDD §22.3, §23.2, ADR 0030).\n" +
                "Generated by `t2 fidelity analyze`; numbers only. The captures themselves stay local (REQ-LEGAL-01)."));
            written.Add(new FactsFile(scenario.Id, path, statuses));
        }

        return written;
    }

    private static void Provenance(YamlWriter p, CaptureSession session, IReadOnlyList<TrialData> trials)
    {
        p.Add("edition", session.ManifestString("install.edition") ?? "unknown");
        p.Add("install_matches_reference", session.ManifestString("install.matches_reference") is { } m ? m == "true" : null);
        p.Add("exe_md5", session.ManifestString("install.exe_md5"));
        p.Add("session", session.ManifestString("session_id") ?? session.Name);
        p.Add("captured_utc", session.ManifestString("started_utc"));
        p.Add("analyzed_utc", DateTime.UtcNow.ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture));
        p.Add("harness", session.ManifestString("harness.version"));
        p.Add("harness_commit", session.ManifestString("harness.commit"));
        p.Add("renderer", session.ManifestString("renderer"));
        p.Add("os", session.ManifestString("machine.os"));
        p.Add("trials", trials.Count);
        p.Add("trials_ok", trials.Count(t => t.Status is "ok" or "partial"));
    }
}
