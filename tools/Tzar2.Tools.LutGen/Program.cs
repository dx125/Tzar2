using System;
using System.Globalization;
using System.IO;
using System.Text;

// Generates the trigonometry lookup tables used by Tzar2.Core.Numerics.Trig.
// Floating point is fine here: this runs once at development time and its output is checked in and
// hash-verified by Tzar2.Core.Tests, so platform differences in Math.Sin/Math.Atan cannot reach the sim.
//
// Usage: dotnet run --project tools/Tzar2.Tools.LutGen -- [output-file]
const int SinEntries = 1024;
const int AtanEntries = 1024;
const double FixedOne = 65536.0;
const double AngleUnitsPerRadian = 65536.0 / (2.0 * Math.PI);

string output = args.Length > 0 ? args[0] : Path.Combine("src", "Tzar2.Core", "Numerics", "TrigTables.g.cs");

var sin = new int[SinEntries];
for (int i = 0; i < SinEntries; i++)
{
    sin[i] = (int)Math.Round(Math.Sin(2.0 * Math.PI * i / SinEntries) * FixedOne, MidpointRounding.AwayFromZero);
}

// atan(i / 1024) for i = 0..1024, in 16-bit binary angle units (the last entry is 45 degrees = 8192).
var atan = new int[AtanEntries + 1];
for (int i = 0; i <= AtanEntries; i++)
{
    atan[i] = (int)Math.Round(Math.Atan((double)i / AtanEntries) * AngleUnitsPerRadian, MidpointRounding.AwayFromZero);
}

var sb = new StringBuilder();
sb.Append("// <auto-generated>\n");
sb.Append("// Generated by tools/Tzar2.Tools.LutGen. Do not edit by hand: regenerate and update the hashes in\n");
sb.Append("// tests/Tzar2.Core.Tests/Numerics/TrigTests.cs.\n");
sb.Append("// </auto-generated>\n\n");
sb.Append("namespace Tzar2.Core.Numerics;\n\n");
sb.Append("internal static class TrigTables\n{\n");
AppendTable(sb, "Sin", $"sin(2*pi*i/{SinEntries}) in Q16.16.", sin);
sb.Append('\n');
AppendTable(sb, "Atan", $"atan(i/{AtanEntries}) for i = 0..{AtanEntries} in 16-bit binary angle units.", atan);
sb.Append("}\n");

File.WriteAllText(output, sb.ToString(), new UTF8Encoding(false));
Console.WriteLine($"Wrote {output}");

static void AppendTable(StringBuilder sb, string name, string summary, int[] values)
{
    sb.Append(CultureInfo.InvariantCulture, $"    /// <summary>{summary}</summary>\n");
    sb.Append(CultureInfo.InvariantCulture, $"    internal static System.ReadOnlySpan<int> {name} => new int[]\n    {{\n");
    for (int i = 0; i < values.Length; i += 8)
    {
        sb.Append("       ");
        for (int j = i; j < Math.Min(i + 8, values.Length); j++)
        {
            sb.Append(CultureInfo.InvariantCulture, $" {values[j]},");
        }

        sb.Append('\n');
    }

    sb.Append("    };\n");
}
